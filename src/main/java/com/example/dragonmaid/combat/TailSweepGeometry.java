   public static List<TailSweepGeometry.Frame> frames(DragonBaseEntity dragon, float yaw) {
      int species = dragon instanceof FireDragonEntity ? 1 : (dragon instanceof LightningDragonEntity ? 2 : 0);
      return frames(species, dragon.isMale(), MiniatureForm.humanoidModelStage(dragon), (double)DragonForms.modelScale(dragon), dragon.position(), yaw);
   }

   public static List<TailSweepGeometry.Frame> attackFrames(DragonBaseEntity dragon, float yaw) {
      List<TailSweepGeometry.Frame> authored = frames(dragon, yaw);
      List<TailSweepGeometry.Frame> attack = new ArrayList<>(authored.size());
      double radius = 0.5;
      double outerCenter = HumanoidTailSweep.reach(dragon) - radius;

      for (TailSweepGeometry.Frame frame : authored) {
         Vec3 tip = frame.trailPoint();
         Vec3 radial = new Vec3(tip.x - dragon.getX(), 0.0, tip.z - dragon.getZ());
         double distance = radial.length();
         Vec3 outward = distance > 1.0E-6
            ? radial.scale(1.0 / distance)
            : new Vec3(-Math.sin(Math.toRadians((double)yaw)), 0.0, Math.cos(Math.toRadians((double)yaw)));
         Vec3 edge = tip.add(outward.scale(Math.max(0.0, outerCenter - distance)));
         List<TailSweepGeometry.Sphere> spheres = new ArrayList<>(frame.spheres());

         for (int link = 0; link < 5; link++) {
            spheres.add(new TailSweepGeometry.Sphere(tip.lerp(edge, (double)link / 4.0), radius));
         }

         attack.add(new TailSweepGeometry.Frame(List.copyOf(spheres), edge));
      }

      return List.copyOf(attack);
   }

   public static List<TailSweepGeometry.Frame> frames(int species, boolean male, int stage, double modelScale, Vec3 origin, float yaw) {
      int index = Math.max(0, Math.min(2, species)) * 6 + (male ? 3 : 0) + Math.max(0, Math.min(2, stage - 3));
      double[][] samples = MODELS[index];
      double angle = Math.toRadians((double)yaw);
      double cosine = Math.cos(angle);
      double sine = Math.sin(angle);
      double scale = modelScale / 16.0;
      List<TailSweepGeometry.Frame> frames = new ArrayList<>(samples.length);

      for (double[] sample : samples) {
         List<TailSweepGeometry.Sphere> spheres = new ArrayList<>(sample.length / 4);

         for (int i = 0; i < sample.length; i += 4) {
            double x = sample[i];
            double y = sample[i + 1];
            double z = sample[i + 2];
            Vec3 point = new Vec3(
               origin.x + (-cosine * x + sine * z) * scale,
               origin.y + y * scale + 0.01 * modelScale,
               origin.z + (-sine * x - cosine * z) * scale
            );
            spheres.add(new TailSweepGeometry.Sphere(point, sample[i + 3] * scale));
         }

         frames.add(new TailSweepGeometry.Frame(List.copyOf(spheres), spheres.get(TRAIL_SPHERES[index]).center()));
      }

      return List.copyOf(frames);
   }

